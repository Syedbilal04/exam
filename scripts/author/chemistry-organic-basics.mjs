function assertAuthoring(items) {
  const errors = [];
  if (items.length !== 197) errors.push(`count ${items.length}, expected 197`);
  if (items[0]?.id !== "che-ob-101") errors.push(`first id ${items[0]?.id}`);
  if (items.at(-1)?.id !== "che-ob-297") errors.push(`last id ${items.at(-1)?.id}`);

  const mix = { easy: 0, medium: 0, hard: 0 };
  const byConcept = {};
  for (const row of items) {
    mix[row.difficulty] = (mix[row.difficulty] ?? 0) + 1;
    byConcept[row.conceptId] ??= { easy: 0, medium: 0, hard: 0, total: 0 };
    byConcept[row.conceptId][row.difficulty] += 1;
    byConcept[row.conceptId].total += 1;
    const stem = String(row.stem ?? "");
    if (stem.length < 20 || stem.length > 420) errors.push(`${row.id}: stem length ${stem.length}`);
    if (new Set(row.options).size !== 4) errors.push(`${row.id}: options not distinct`);
  }
  for (const [conceptId, want] of Object.entries(expected)) {
    const got = byConcept[conceptId] ?? { easy: 0, medium: 0, hard: 0, total: 0 };
    for (const d of ["easy", "medium", "hard"]) {
      if (got[d] !== want[d]) errors.push(`${conceptId} ${d} ${got[d]}, expected ${want[d]}`);
    }
  }

  const bankPath = path.join(import.meta.dirname, "..", ".bank-stems.json");
  const bank = JSON.parse(readFileSync(bankPath, "utf8"));
  for (let i = 0; i < items.length; i++) {
    for (let j = i + 1; j < items.length; j++) {
      if (stemsClash(items[i].stem, items[j].stem)) {
        errors.push(`${items[i].id} clashes with ${items[j].id}`);
      }
    }
    for (const row of bank) {
      if (stemsClash(items[i].stem, row.stem)) {
        errors.push(`${items[i].id} clashes with bank ${row.id}`);
      }
    }
  }

  if (errors.length) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  console.log(`authored ${items.length}  easy ${mix.easy}  medium ${mix.medium}  hard ${mix.hard}`);
}


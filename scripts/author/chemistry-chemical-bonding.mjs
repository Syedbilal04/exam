function q(conceptId, difficulty, stem, options, answerIndex, explanation) {
  return item({
    prefix,
    index: n++,
    chapterId,
    conceptId,
    difficulty,
    stem,
    options,
    answerIndex,
    explanation,
  });
}

function fail(message) {
  throw new Error(message);
}

const questions = drafts.map((row) => q(...row));

if (questions.length !== 176) {
  fail(`expected 176 questions, got ${questions.length}`);
}
if (questions[0].id !== "che-cb-101" || questions.at(-1).id !== "che-cb-276") {
  fail(`ids are ${questions[0].id} .. ${questions.at(-1).id}`);
}

for (const [conceptId, expected] of Object.entries(EXPECTED)) {
  const slice = questions.filter((row) => row.conceptId === conceptId);
  const counts = { easy: 0, medium: 0, hard: 0 };
  for (const row of slice) counts[row.difficulty] += 1;
  const total = expected.easy + expected.medium + expected.hard;
  if (slice.length !== total) {
    fail(`${conceptId}: ${slice.length} items, expected ${total}`);
  }
  for (const difficulty of ["easy", "medium", "hard"]) {
    if (counts[difficulty] !== expected[difficulty]) {
      fail(
        `${conceptId} ${difficulty}: ${counts[difficulty]}, expected ${expected[difficulty]}`,
      );
    }
  }
}

for (const question of questions) {
  const stem = question.stem;
  if (stem.length < 20 || stem.length > 420) {
    fail(`${question.id}: stem length ${stem.length} (${stem.slice(0, 60)})`);
  }
  if (new Set(question.options).size !== 4) {
    fail(`${question.id}: options are not distinct`);
  }
  if (
    question.answerIndex < 0 ||
    question.answerIndex > 3 ||
    !question.explanation?.trim()
  ) {
    fail(`${question.id}: bad answerIndex or explanation`);
  }
}

for (let i = 0; i < questions.length; i += 1) {
  for (let j = i + 1; j < questions.length; j += 1) {
    if (stemsClash(questions[i].stem, questions[j].stem)) {
      fail(`internal clash ${questions[i].id} / ${questions[j].id}`);
    }
  }
}

const bankStems = JSON.parse(readFileSync(bankStemsFile, "utf8"));
for (const question of questions) {
  const hit = bankStems.find((row) => stemsClash(question.stem, row.stem));
  if (hit) {
    fail(`${question.id} clashes with ${hit.id}: ${hit.stem}`);
  }
}

const payload = pack(questions);
mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, `${JSON.stringify(payload, null, 2)}\n`, "utf8");

const mix = { easy: 0, medium: 0, hard: 0 };
for (const question of questions) mix[question.difficulty] += 1;
console.log(`wrote ${questions.length} questions to ${path.relative(root, outFile)}`);
console.log(`ids ${questions[0].id} .. ${questions.at(-1).id}`);
console.log(`mix easy=${mix.easy} medium=${mix.medium} hard=${mix.hard}`);
for (const conceptId of Object.keys(EXPECTED)) {
  const slice = questions.filter((row) => row.conceptId === conceptId);
  const counts = { easy: 0, medium: 0, hard: 0 };
  for (const row of slice) counts[row.difficulty] += 1;
  console.log(
    `  ${conceptId}: ${slice.length} (e${counts.easy}/m${counts.medium}/h${counts.hard})`,
  );
}
